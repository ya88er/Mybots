import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { startBackend } from '../../src/backend/backend-host.ts';
import { startGate } from '../../src/backend/backend-gate.ts';
import { ToolDispatch, wireName } from '../../src/tools/tool-dispatch.ts';

// These tests drive the **real** upstream Mini App and its **real** business
// tools. The authority rule is the important claim: a model must not gain
// another Bot's powers by naming it in its arguments.

async function fixture(t: { after: (fn: () => unknown) => void }) {
  const root = await mkdtemp(join(tmpdir(), 'minibots-tools-'));
  const token = 'tool-test-token';

  const backend = await startBackend({
    dataDir: join(root, 'data'),
    sessionDir: join(root, 'sessions'),
    agentDir: join(root, 'agent'),
    token,
    log: () => {},
  });

  const gate = await startGate({
    upstream: { host: backend.ready.host, port: backend.ready.port },
    token,
  });

  t.after(async () => {
    await gate.stop();
    await backend.stop();
    await rm(root, { recursive: true, force: true }).catch(() => {});
  });

  const call = async (path: string, init?: RequestInit) => {
    const response = await fetch(`http://127.0.0.1:${gate.port}${path}`, {
      ...init,
      headers: {
        authorization: `Bearer ${token}`,
        ...(init?.headers ?? {}),
      },
    });
    const text = await response.text();
    let body: unknown = text;
    try {
      body = JSON.parse(text);
    } catch {
      // Not JSON.
    }
    return { status: response.status, body };
  };

  return { root, token, gate, backend, call };
}

test('all 21 upstream business tools are offered to the model', async (t) => {
  const h = await fixture(t);

  // The upstream MCP endpoint lists them.
  const response = await fetch(`http://127.0.0.1:${h.gate.port}/mcp/minimax-bot`, {
    method: 'POST',
    headers: {
      authorization: `Bearer ${h.token}`,
      'content-type': 'application/json',
      accept: 'application/json',
    },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/list', params: {} }),
  });
  const body = (await response.json()) as {
    result?: { tools?: Array<{ name: string }> };
  };
  const names = (body.result?.tools ?? []).map((tool) => tool.name);

  // The implementation plan lists 21: 19 declared literally, plus
  // `get_tasks` and `cancel_tasks`, which are generated by a `.map()`.
  assert.equal(names.length, 21, `the upstream offers 21 tools, got ${names.length}`);
  for (const expected of [
    'list_team',
    'message_bot',
    'dispatch_tasks',
    'get_tasks',
    'cancel_tasks',
    'post_group',
    'start_helper',
    'list_helpers',
    'stop_helper',
    'remember',
    'forget',
    'recall',
    'create_bot',
    'update_bot',
    'delete_bot',
    'create_group',
    'update_group',
    'delete_group',
    'create_schedule',
    'list_schedules',
    'delete_schedule',
  ]) {
    assert.ok(names.includes(expected), `${expected} is offered`);
  }
});

test('the tool dispatch replaces a model-supplied caller', async (t) => {
  const h = await fixture(t);

  // A dispatch bound to a caller, as the backend builds it.
  const calls: Array<{ name: string; args: Record<string, unknown>; caller: unknown }> = [];
  const dispatch = new ToolDispatch({
    dispatch: {
      definitions: () => [
        { name: 'list_team', description: 'List the team.', inputSchema: { type: 'object' } },
      ],
      names: () => ['list_team'],
      call: async (name, args, options) => {
        calls.push({ name, args, caller: options?.caller });
        return { ok: true };
      },
      failureText: () => 'failed',
    },
    resolveCaller: () => ({ id: 'bot_real', chatId: 'chat1', sessionId: 'sess1', runId: 'run1' }),
  });

  const tools = dispatch.tools();
  assert.equal(tools.length, 1);
  assert.equal(tools[0]?.name, wireName('list_team'), 'the canonical UI label is preserved');

  // The model claims to be somebody else.
  const result = await tools[0]!.execute(
    { caller_bot_id: 'bot_chief' },
    { botId: 'bot_real', chatId: 'chat1', sessionId: 'sess1', runId: 'run1' },
  );

  assert.ok(!result.isError, 'the call succeeded');
  assert.equal(calls.length, 1);
  assert.equal(
    calls[0]?.args.caller_bot_id,
    undefined,
    "the model's caller field was removed, not trusted",
  );
  assert.equal(
    (calls[0]?.caller as { id?: string } | undefined)?.id,
    'bot_real',
    'the bound caller was used',
  );
});

test('a tool call for a session with no Bot is refused', async (t) => {
  const h = await fixture(t);

  const dispatch = new ToolDispatch({
    dispatch: {
      definitions: () => [
        { name: 'list_team', description: 'List the team.', inputSchema: { type: 'object' } },
      ],
      names: () => ['list_team'],
      call: async () => ({ ok: true }),
      failureText: () => 'failed',
    },
    resolveCaller: () => undefined,
  });

  const tools = dispatch.tools();
  const result = await tools[0]!.execute({}, {
    botId: 'bot_real',
    chatId: 'chat1',
    sessionId: 'sess-unknown',
    runId: 'run1',
  });

  assert.equal(result.isError, true, 'the call was refused');
  assert.match(result.content, /no Bot bound/);
});

