test('a Bot cannot act for another Bot through the model', async (t) => {
  const h = await fixture(t);

  // The store seeds a main Bot called Chief, and the app's operator creates
  // the others.
  const other = await h.call('/api/bots', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ name: 'Other', role: 'Helper' }),
  });
  assert.equal(other.status, 200, `the other Bot was created: ${JSON.stringify(other.body)}`);

  const state = await h.call('/api/state');
  const bots = (state.body as { bots: Array<{ id: string; name: string; isMain?: boolean }> }).bots;
  const chiefBot = bots.find((bot) => bot.isMain) ?? bots.find((bot) => bot.name === 'Chief');
  const otherBot = bots.find((bot) => bot.name === 'Other');
  assert.ok(chiefBot, 'the Chief exists');
  assert.ok(otherBot, 'the other Bot exists');

  // The dispatch is bound to the *other* Bot.
  const seen: Array<unknown> = [];
  const dispatch = new ToolDispatch({
    dispatch: {
      definitions: () => [
        { name: 'delete_bot', description: 'Delete a Bot.', inputSchema: { type: 'object' } },
      ],
      names: () => ['delete_bot'],
      call: async (_name, args, options) => {
        seen.push({ args, caller: options?.caller });
        return { ok: true };
      },
      failureText: () => 'failed',
    },
    resolveCaller: () => ({
      id: otherBot!.id,
      chatId: 'chat1',
      sessionId: 'sess1',
      runId: 'run1',
    }),
  });

  const tools = dispatch.tools();
  // The model names the Chief as the caller and the Chief as the target.
  await tools[0]!.execute(
    { caller_bot_id: chiefBot!.id, bot: chiefBot!.id },
    { botId: otherBot!.id, chatId: 'chat1', sessionId: 'sess1', runId: 'run1' },
  );

  assert.equal(seen.length, 1);
  assert.equal(
    (seen[0] as { args: Record<string, unknown> }).args.caller_bot_id,
    undefined,
    "the model's caller field was dropped",
  );
  assert.equal(
    (seen[0] as { caller: { id?: string } }).caller.id,
    otherBot!.id,
    'the call ran as the session\'s own Bot, not the Chief',
  );
});
